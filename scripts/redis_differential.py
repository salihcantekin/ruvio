UNORDERED = {b"KEYS", b"SMEMBERS", b"SINTER", b"SUNION", b"SDIFF", b"HKEYS", b"HVALS"}


def normalize(name: bytes, response):
    if name in UNORDERED and response[0] == b"*":
        items = response[1]
        if isinstance(items, list):
            return response[0], sorted(items, key=lambda item: item[1] or b"")
    if name == b"HGETALL" and response[0] == b"*":
        items = response[1]
        if isinstance(items, list):
            pairs = list(zip(items[0::2], items[1::2]))
            pairs.sort(key=lambda pair: pair[0][1] or b"")
            flattened = []
            for field, value in pairs:
                flattened.extend((field, value))
            return response[0], flattened
    return response


