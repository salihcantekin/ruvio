COMMANDS = COMMANDS + COLLECTIONS + LISTS


def same_float(name, actual, expected) -> bool:
    """INCRBYFLOAT/HINCRBYFLOAT print 16 digits here and 17 in Redis (documented difference)."""
    if name not in (b"INCRBYFLOAT", b"HINCRBYFLOAT"):
        return False
    try:
        return abs(float(actual[1]) - float(expected[1])) < 1e-9
    except (TypeError, ValueError, IndexError):
        return False


def connect(host: str, port: int):
    wait_ready(port, host=host)
    # The timeout only stops a lost reply from hanging the check.
    connection = socket.create_connection((host, port), timeout=10)
    return connection, connection.makefile("rwb", buffering=0)


def run(host: str, ruvio_port: int, redis_port: int, commands=None):
    ruvio_connection, ruvio = connect(host, ruvio_port)
    redis_connection, redis = connect(host, redis_port)
    try:
        # Both start empty, whatever an earlier check or a restart left behind.
        for stream in (ruvio, redis):
            assert request(stream, b"FLUSHALL") == (b"+", b"OK")
        for command in commands or COMMANDS:
            frame = encode(*command)
            # Ruvio scripts call `ruvio.call`; Redis names the same table `redis`.
            redis_frame = encode(*(part.replace(b"ruvio.call", b"redis.call") for part in command))
            ruvio.write(frame)
            redis.write(redis_frame)
            ruvio.flush()
            redis.flush()
            actual = normalize(command[0], read_response(ruvio))
            expected = normalize(command[0], read_response(redis))
            if actual != expected and not same_float(command[0], actual, expected):
                raise AssertionError(
                    f"{command[0]!r} differs: Ruvio={actual!r}, Redis={expected!r}"
                )
    finally:
        ruvio_connection.close()
        redis_connection.close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--ruvio-port", type=int, default=6379)
    parser.add_argument("--redis-port", type=int, default=6380)
    parser.add_argument("--group", choices=sorted(GROUPS), help="run only one command group")
    args = parser.parse_args()
    run(args.host, args.ruvio_port, args.redis_port, GROUPS.get(args.group))
