#!/usr/bin/env python3
"""Regenerates Cmd.java (pre-encoded command words) and RuvioSyncCommands.java (blocking facade).

Run from anywhere: python3 clients/java/tools/generate.py
The async command families are the source of truth; the blocking facade mirrors every public
CompletableFuture method of them.
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "main", "java",
                    "io", "github", "salihcantekin", "ruvio")
COMMANDS = os.path.join(ROOT, "commands")
CMD_PATH = os.path.join(ROOT, "internal", "Cmd.java")
SYNC_PATH = os.path.join(COMMANDS, "RuvioSyncCommands.java")
CHAIN = ["BaseCommands", "StringCommands", "KeyCommands", "HashCommands", "ListCommands",
         "SetCommands", "SortedSetCommands", "GeoCommands", "StreamCommands", "JsonCommands",
         "ScriptingCommands", "RuvioCommands"]
BANNER = "// SPDX-License-Identifier: MIT\n// GENERATED by tools/generate.py. Do not edit by hand.\n"


def word_for(ident):
    if ident.startswith("JSON_"):
        return "JSON." + ident[5:]
    if ident.startswith("BF_"):
        return "BF." + ident[3:]
    return ident


def gen_cmd():
    idents = set()
    for directory, _, files in os.walk(ROOT):
        for name in files:
            if name.endswith(".java") and name != "Cmd.java":
                with open(os.path.join(directory, name)) as source:
                    idents.update(re.findall(r"\bCmd\.([A-Z][A-Z0-9_]*)\b", source.read()))
    lines = [BANNER, "package io.github.salihcantekin.ruvio.internal;\n\n",
             "/**\n * Command and keyword words pre-encoded as complete RESP bulk fragments ({@code $3\\r\\nGET\\r\\n}).\n * Internal: not part of the supported API.\n */\n",
             "public final class Cmd {\n    private Cmd() {\n    }\n\n"]
    for ident in sorted(idents):
        lines.append('    /** The word {@code %s}, pre-encoded as a RESP bulk string. */\n' % word_for(ident))
        lines.append('    public static final byte[] %s = RespOut.fragment("%s");\n' % (ident, word_for(ident)))
    lines.append("}\n")
    return "".join(lines), len(idents)


def split_params(params):
    out, depth, cur = [], 0, ""
    for ch in params:
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


METHOD = re.compile(r"((?:[ \t]*/\*\*(?:(?!\*/).)*\*/\n)?)((?:[ \t]*@\w+\n)*)[ \t]*public (final )?CompletableFuture<", re.S)


def methods(src):
    for m in METHOD.finditer(src):
        i = m.end()
        depth = 1
        while depth:
            if src[i] == "<":
                depth += 1
            elif src[i] == ">":
                depth -= 1
            i += 1
        ret = src[m.end():i - 1]
        rest = src[i:]
        mm = re.match(r"\s*(\w+)\((.*?)\)\s*\{", rest, re.S)
        if not mm:
            continue
        doc = m.group(1)
        annotations = m.group(2)
        yield doc, annotations, ret, mm.group(1), mm.group(2)


def gen_sync():
    body = []
    seen = set()
    imports = set()
    count = 0
    for cls in CHAIN:
        with open(os.path.join(COMMANDS, cls + ".java")) as source:
            src = source.read()
        imports.update(re.findall(r"^import (io\.github\.salihcantekin\.ruvio\.(?:args|model)\.\w+);", src, re.M))
        body.append("\n    // ---- %s ----\n" % cls)
        for doc, annotations, ret, name, params in methods(src):
            plist = split_params(params)
            sig = (name, tuple(re.sub(r"\s+\w+$", "", p) for p in plist))
            if sig in seen:
                continue
            seen.add(sig)
            count += 1
            names = [re.sub(r".*\s", "", p) for p in plist]
            generic_varargs = any(re.search(r"\b[KV](<[^>]*>)?\.\.\.", p) or re.search(r"GeoValue<V>\.\.\.", p) for p in plist)
            if doc and ret == "Void":
                # the blocking method returns nothing, so the async-only @return line goes
                doc = re.sub(r"[ \t]*\*[ \t]*@return[^\n]*(?:\n(?![ \t]*\*[ \t]*(?:@|/|\n)|[ \t]*\*/)[^\n]*)*\n", "", doc)
            if doc:
                body.append(doc)
            mods = "public final " if generic_varargs else "public "
            if generic_varargs:
                body.append("    @SafeVarargs\n")
            call = "async.%s(%s)" % (name, ", ".join(names))
            if ret == "Void":
                body.append("    %svoid %s(%s) {\n        await(%s);\n    }\n\n" % (mods, name, ", ".join(plist), call))
            else:
                body.append("    %s%s %s(%s) {\n        return await(%s);\n    }\n\n" % (mods, ret, name, ", ".join(plist), call))
    text = "".join(body)
    used = sorted(i for i in imports if re.search(r"\b%s\b" % i.rsplit(".", 1)[1], text))
    header = ["import io.github.salihcantekin.ruvio.RuvioAsync;",
              "import io.github.salihcantekin.ruvio.RuvioConnectionException;",
              "import io.github.salihcantekin.ruvio.RuvioServerException;"]
    header += ["import %s;" % i for i in used]
    src = BANNER + "package io.github.salihcantekin.ruvio.commands;\n\n" + "\n".join(header) + """

import java.time.Duration;
import java.util.List;
import java.util.Map;
import java.util.concurrent.CompletableFuture;

/**
 * Blocking facade over {@link RuvioAsync}: every method sends the typed command on the shared
 * multiplexed connection and waits for its reply. The method docs describe the value returned.
 *
 * <p>Errors surface as unchecked exceptions: a {@code -ERR ...} reply (for example {@code WRONGTYPE}
 * when a key holds another type) is a {@link RuvioServerException} whose {@code code()} is the first
 * word; a socket failure is a {@link RuvioConnectionException} (the command may or may not have run);
 * waiting longer than {@code commandTimeoutMillis} from the options fails with a
 * {@link io.github.salihcantekin.ruvio.RuvioException}. {@code null} arguments for keys and values are
 * refused with {@link IllegalArgumentException} before anything is sent.
 *
 * <p>In a cluster, keyless commands ({@code DBSIZE}, {@code FLUSHDB}, {@code KEYS}, {@code SCAN},
 * {@code INFO} and so on) go to the seed node only; use {@code RuvioClient#onNode} to reach another node.
 * A command whose keys span slots fails with {@code CROSSSLOT} unless it is one of the commands the
 * client splits per slot ({@code MGET}, {@code MSET}, {@code DEL}, {@code EXISTS}, {@code UNLINK},
 * {@code TOUCH}), whose parts are not atomic. Blocking server commands ({@code BLPOP}, {@code XREAD BLOCK},
 * {@code FILLGET ... WAIT}) hold the shared connection while they wait: run them on
 * {@code RuvioClient#dedicated()}.
 *
 * @param <K> key type (also hash fields and stream field names)
 * @param <V> value type (also set and sorted-set members, list elements and stream field values)
 */
public abstract class RuvioSyncCommands<K, V> {
    /** The asynchronous API every method delegates to. */
    protected final RuvioAsync<K, V> async;

    /**
     * Creates the facade over an asynchronous command set.
     *
     * @param async the asynchronous commands to wrap
     */
    protected RuvioSyncCommands(RuvioAsync<K, V> async) {
        this.async = async;
    }

    /**
     * Waits for a reply, honouring the command timeout, and rethrows failures as unchecked exceptions.
     *
     * @param future the pending reply
     * @param <T> the reply type
     * @return the reply value
     */
    protected abstract <T> T await(CompletableFuture<T> future);
""" + text.rstrip() + "\n}\n"
    return src, count


def main():
    """Write both files, or with --check fail when a checked-in file differs from its source."""
    check = "--check" in sys.argv[1:]
    stale = []
    for path, (text, count), label in ((CMD_PATH, gen_cmd(), "Cmd words"),
                                       (SYNC_PATH, gen_sync(), "sync methods")):
        print("%s: %d" % (label, count))
        with open(path) as current:
            same = current.read() == text
        if check:
            if not same:
                stale.append(os.path.relpath(path))
        elif not same:
            with open(path, "w") as out:
                out.write(text)
    if stale:
        print("out of date, run clients/java/tools/generate.py: " + ", ".join(stale))
        sys.exit(1)


if __name__ == "__main__":
    main()
